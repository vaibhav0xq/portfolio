#!/usr/bin/env node
// Turns the owner's name set in Caveat into SVG path data for the preloader, which strokes the
// outlines as if a pen were writing them. Run once: node scripts/gen-name-path.mjs /path/to/Caveat.ttf
import { readFileSync, writeFileSync } from 'node:fs';
import opentype from 'opentype.js';

const file = process.argv[2];
if (!file) throw new Error('pass the Caveat ttf path');
const font = opentype.parse(readFileSync(file).buffer);
const size = 120;
const words = ['Vaibhav', 'Gangani'];
const paths = [];
let x = 0;
for (const word of words) {
  const glyphs = font.stringToGlyphs(word);
  for (let i = 0; i < glyphs.length; i++) {
    const g = glyphs[i];
    const p = g.getPath(x, 0, size);
    paths.push(p.toPathData(1));
    x += (g.advanceWidth / font.unitsPerEm) * size;
    if (i < glyphs.length - 1) x += (font.getKerningValue(g, glyphs[i + 1]) / font.unitsPerEm) * size;
  }
  x += size * 0.32;
}
const width = Math.ceil(x);
const ascent = (font.ascender / font.unitsPerEm) * size;
const descent = (Math.abs(font.descender) / font.unitsPerEm) * size;
const out = `// Generated by scripts/gen-name-path.mjs from Caveat (OFL). One path per letter, in writing order.
export const nameGlyphs: string[] = ${JSON.stringify(paths)};
export const nameBox = { width: ${width}, ascent: ${ascent.toFixed(1)}, descent: ${descent.toFixed(1)} };
`;
writeFileSync(new URL('../src/content/name-path.ts', import.meta.url), out);
console.log('letters', paths.length, 'width', width);
